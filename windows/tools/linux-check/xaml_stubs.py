#!/usr/bin/env python3
"""Linux-only C# type check for the WinUI app: the XAML compiler only runs on Windows, so this writes
the partial classes it would generate (InitializeComponent + x:Name fields + event handler checks).
Usage: python3 xaml_stubs.py <app dir> <out file>"""
import os, re, sys, xml.etree.ElementTree as ET

X = '{http://schemas.microsoft.com/winfx/2006/xaml}'
app, out = sys.argv[1], sys.argv[2]
code = ['// <auto-generated/> stubs for the Linux type check\n#nullable disable',
        'using Microsoft.UI.Xaml; using Microsoft.UI.Xaml.Controls; using Microsoft.UI.Xaml.Controls.Primitives;',
        'using Microsoft.UI.Xaml.Shapes; using Microsoft.UI.Xaml.Media; using Microsoft.UI.Xaml.Documents;']
for root, dirs, files in os.walk(app):
    dirs[:] = [d for d in dirs if d not in ('obj', 'bin')]
    for f in files:
        if not f.endswith('.xaml'): continue
        tree = ET.parse(os.path.join(root, f)).getroot()
        cls = tree.get(X + 'Class')
        if not cls: continue
        ns, name = cls.rsplit('.', 1)
        # xmlns prefixes "using:Foo" → namespace Foo
        raw = open(os.path.join(root, f), encoding='utf-8').read()
        using = dict(re.findall(r'xmlns:?(\w*)="using:([\w.]+)"', raw))
        fields, handlers = [], []
        for el in tree.iter():
            tag = el.tag
            m = re.match(r'\{(.*)\}(.*)', tag)
            uri, local = (m.group(1), m.group(2)) if m else ('', tag)
            if '.' in local: continue   # property element
            n = el.get(X + 'Name') or el.get('Name') if el is not tree else None
            if n:
                t = local
                if uri.startswith('using:'): t = 'global::' + uri[6:] + '.' + local
                fields.append(f'    internal {t} {n};')
            for k, v in el.attrib.items():
                if k.startswith('{') or not re.fullmatch(r'[A-Za-z_]\w*', v or ''): continue
                if re.fullmatch(r'(Click|Toggled|Checked|Unchecked|SelectionChanged|TextChanged|Loaded|Unloaded|Tapped|ItemClick|ValueChanged|QuerySubmitted|PointerPressed|SizeChanged|Closed|Activated|KeyDown|DoubleTapped|RightTapped|Opened|Expanding|Collapsed|ItemInvoked|PaneClosed|Invoked|SelectedIndexChanged|ToggleChanged)', k):
                    handlers.append(f'    // {local}.{k}="{v}"\n    void __check_{v}_{len(handlers)}() {{ _ = (System.Delegate){v}; }}')
        code.append(f'namespace {ns} {{ partial class {name} {{\n    void InitializeComponent() {{ }}\n' + '\n'.join(fields + handlers) + '\n} }')
code.append('namespace Fusebox.App { static class BuildInfo { public const long Build = 0; public const string Version = "0.0.0"; } }')
open(out, 'w').write('\n'.join(code) + '\n')
